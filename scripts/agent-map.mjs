function relativePath(absolute) {
  return relative(ROOT, absolute).split("\\").join("/");
}

function gitFiles() {
  return execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard"], {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  })
    .trim()
    .split("\n")
    .filter(Boolean);
}

function isSourcePath(path) {
  if (EXCLUDED_PREFIXES.some((prefix) => path.startsWith(prefix))) return false;
  if (path.includes("/node_modules/")) return false;
  return SOURCE_EXTENSION.test(path);
}

function sourceFiles() {
  return gitFiles().filter((path) => isSourcePath(path) && existsSync(join(ROOT, path))).sort();
}

function languageOf(path) {
  const ext = path.slice(path.lastIndexOf(".") + 1).toLowerCase();
  const languages = {
    ts: "TypeScript",
    tsx: "TSX",
    js: "JavaScript",
    mjs: "JavaScript",
    cjs: "JavaScript",
    rs: "Rust",
    py: "Python",
    yml: "YAML",
    yaml: "YAML",
    css: "CSS",
    json: "JSON",
    html: "HTML",
    xml: "XML",
  };
  return languages[ext] ?? ext.toUpperCase();
}

function readRepoFile(path) {
  return readFileSync(join(ROOT, path), "utf8");
}

function commandNames() {
  const source = readRepoFile("src-tauri/src/lib.rs");
  const start = source.indexOf("generate_handler![");
  if (start < 0) throw new Error("找不到 generate_handler![ 命令注册块");
  let depth = 0;
  let end = -1;
  for (let index = start + "generate_handler!".length; index < source.length; index += 1) {
    if (source[index] === "[") depth += 1;
    if (source[index] === "]") {
      depth -= 1;
      if (depth === 0) {
        end = index;
        break;
      }
    }
  }
  if (end < 0) throw new Error("generate_handler![ 未闭合");
  return source
    .slice(start + "generate_handler![".length, end)
    .split(",")
    .map((part) => part.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "").trim())
    .filter(Boolean);
}

function mcpToolNames() {
  const source = readRepoFile("src-tauri/src/mcp/specs.rs");
  return [...new Set([...source.matchAll(/name:\s*"([^"]+)"/g)].map((match) => match[1]))];
}

function gateNames() {
  const pkg = JSON.parse(readRepoFile("package.json"));
  return Object.keys(pkg.scripts ?? {}).filter((name) => /^(test|check|verify|locate|build)/.test(name));
}

function rustTestFiles() {
  return sourceFiles()
    .filter((path) => path.endsWith(".rs") && readRepoFile(path).includes("#[cfg(test)]"))
    .map((path) => {
      const tests = readRepoFile(path).match(/#\[(?:tokio::)?test\]/g) ?? [];
      return { path, count: tests.length };
    });
}

function docsRegistry() {
  const docs = gitFiles().filter((path) => (path.startsWith("docs/") || /^[^/]+\.md$/.test(path)) && existsSync(join(ROOT, path)));
  if (!docs.includes("docs/AGENT_MAP.md")) docs.push("docs/AGENT_MAP.md");
  return docs.sort().map((path) => {
    const entry = DOC_STATUS.get(path);
    if (!entry) throw new Error(`文档未登记：${path}（请在 scripts/agent-map.mjs 的 DOC_STATUS 添加状态与用途）`);
    return { path, status: entry[0], purpose: entry[1] };
  });
}

function indexRows() {
  return readRepoFile("docs/BUSINESS_INDEX.md")
    .split("\n")
    .filter((line) => line.startsWith("|") && !line.startsWith("| ---"));
}

function indexDigest() {
  return createHash("sha256").update(indexRows().join("\n")).digest("hex").slice(0, 12);
}

function runCodegraph(args, maxBuffer = 64 * 1024 * 1024) {
  return execFileSync("codegraph", args, {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer,
    stdio: ["ignore", "pipe", "pipe"],
  });
}

function codegraphSnapshot() {
  let status;
  let files;
  let nodes;
  try {
    status = JSON.parse(runCodegraph(["status", "--json"]));
    files = JSON.parse(runCodegraph(["files", "--json"]));
    nodes = JSON.parse(runCodegraph(["query", "", "-l", "8000", "--json"]));
  } catch (error) {
    throw new Error(`CodeGraph CLI 不可用或输出异常：${error.message}。生成前请先启动 codegraph 索引。`);
  }
  const byFile = new Map(files.map((file) => [file.path, file]));
  const symbols = new Map();
  for (const item of nodes) {
    const node = item.node ?? item;
    if (!DEFINITION_KINDS.has(node.kind) || !node.name || !node.filePath) continue;
    if (!symbols.has(node.filePath)) symbols.set(node.filePath, []);
    symbols.get(node.filePath).push({ name: node.name, line: node.startLine ?? 0 });
  }
  return { status, byFile, symbols };
}

function representativeSymbols(symbols, path) {
  const unique = new Map();
  for (const symbol of symbols.get(path) ?? []) {
    if (!unique.has(symbol.name)) unique.set(symbol.name, symbol.line);
  }
  return [...unique.entries()]
    .sort((left, right) => left[1] - right[1] || left[0].localeCompare(right[0]))
    .slice(0, 5)
    .map(([name]) => name);
}

function generate() {
  const { status, byFile, symbols } = codegraphSnapshot();
  const files = sourceFiles();
  const commands = commandNames();
  const tools = mcpToolNames();
  const gates = gateNames();
  const tests = rustTestFiles();
  const docs = docsRegistry();
  const lines = [
    MAP_MARKER,
    "# ClipForge Agent 项目地图（生成）",
    "",
    "> 本文件由 `scripts/agent-map.mjs` 生成，禁止手工编辑。修改源码、命令、MCP 工具、门禁或文档清单后运行 `pnpm docs:map` 重新生成；`pnpm docs:map:check` 已挂入 `pnpm test:unit`。",
    "> 路由以 `docs/BUSINESS_INDEX.md` 为权威来源；本地图只做 CodeGraph 符号展开与完整性快照。",
    "",
    "## 快照",
    "",
    `- CodeGraph 已索引文件: ${status.fileCount ?? files.length}`,
    `- CodeGraph 节点: ${status.nodeCount ?? 0}`,
    `- CodeGraph 边: ${status.edgeCount ?? 0}`,
    `- 受管源码 / 配置文件: ${files.length}`,
    `- Tauri commands: ${commands.length}`,
    `- MCP tools: ${tools.length}`,
    `- 测试与门禁脚本: ${gates.length}`,
    `- Rust 测试文件: ${tests.length}`,
    `- 文档登记: ${docs.length}`,
    "",
    "## 路由表（来自 BUSINESS_INDEX.md）",
    "",
    `- 索引摘要: ${indexDigest()}`,
    "",
    ...indexRows(),
    "",
    `## 源码文件清单（${files.length}）`,
    "",
    "| 文件 | 语言 | CodeGraph 节点 | 代表符号 |",
    "| --- | --- | ---: | --- |",
  ];
  for (const path of files) {
    const names = representativeSymbols(symbols, path);
    const nodeCount = byFile.get(path)?.nodeCount ?? 0;
    const symbolColumn = names.length ? names.map((name) => `\`${name}\``).join(" ") : "—";
    lines.push(`| \`${path}\` | ${languageOf(path)} | ${nodeCount} | ${symbolColumn} |`);
  }
  lines.push("", `## Tauri commands（${commands.length}）`, "");
  for (const name of commands) lines.push(`- \`${name}\` — \`src-tauri/src/lib.rs\``);
  lines.push("", `## MCP tools（${tools.length}）`, "");
  for (const name of tools) lines.push(`- \`${name}\` — \`src-tauri/src/mcp/specs.rs\``);
  lines.push("", `## 测试与门禁脚本（${gates.length}）`, "");
  for (const name of gates) lines.push(`- \`${name}\` — \`package.json\``);
  lines.push("", `## Rust 测试文件（${tests.length}）`, "");
  for (const test of tests) lines.push(`- \`${test.path}\` — ${test.count} 个 test`);
  lines.push("", `## 文档登记（${docs.length}）`, "", "| 文档 | 状态 | 用途 |", "| --- | --- | --- |");
  for (const doc of docs) lines.push(`| \`${doc.path}\` | ${doc.status} | ${doc.purpose} |`);
  lines.push("");
  writeFileSync(MAP_PATH, lines.join("\n"), "utf8");
  console.log(
    `[agent-map] 已生成 docs/AGENT_MAP.md：源码 ${files.length}，命令 ${commands.length}，工具 ${tools.length}，文档 ${docs.length}`,
  );
}

function sectionLines(text, heading) {
  const lines = text.split("\n");
  const start = lines.findIndex((line) => line.startsWith(`## ${heading}`));
  if (start < 0) throw new Error(`项目地图缺少章节：${heading}`);
  const end = lines.findIndex((line, index) => index > start && line.startsWith("## "));
  return lines.slice(start + 1, end < 0 ? lines.length : end);
}

function firstCode(paths, label) {
  return paths.map((path) => {
    const match = path.match(/`([^`]+)`/);
    if (!match) throw new Error(`${label} 行缺少反引号路径：${path}`);
    return match[1];
  });
}

function assertSet(actual, expected, label) {
  const missing = expected.filter((item) => !actual.includes(item));
  const extra = actual.filter((item) => !expected.includes(item));
  if (missing.length || extra.length) {
    throw new Error(
      `${label} 漂移：缺少 [${missing.join(", ")}]，多余 [${extra.join(", ")}]；请运行 pnpm docs:map`,
    );
  }
}

function check() {
  const text = readFileSync(MAP_PATH, "utf8");
  if (!text.startsWith(MAP_MARKER)) throw new Error("docs/AGENT_MAP.md 不是本生成器生成的，禁止手改");

  const files = sourceFiles();
  const knownRoots = new Set(gitFiles().map((path) => path.split("/")[0]));
  const sourceRows = sectionLines(text, "源码文件清单").filter((line) => line.startsWith("| `"));
  assertSet(firstCode(sourceRows, "源码清单"), files, "源码文件清单");
  for (const row of sourceRows) {
    const [path, ...symbolCells] = [...row.matchAll(/`([^`]+)`/g)].map((match) => match[1]);
    const source = readRepoFile(path);
    for (const symbol of symbolCells) {
      if (!source.includes(symbol)) throw new Error(`${path} 中找不到地图符号 ${symbol}；请运行 pnpm docs:map`);
    }
  }

  const digestLine = sectionLines(text, "路由表").find((line) => line.startsWith("- 索引摘要:"));
  if (!digestLine || digestLine.trim() !== `- 索引摘要: ${indexDigest()}`) {
    throw new Error("BUSINESS_INDEX.md 已变化；请运行 pnpm docs:map");
  }

  const commandRows = sectionLines(text, "Tauri commands").filter((line) => line.startsWith("- `"));
  assertSet(firstCode(commandRows, "Tauri commands"), commandNames(), "Tauri commands");
  const toolRows = sectionLines(text, "MCP tools").filter((line) => line.startsWith("- `"));
  assertSet(firstCode(toolRows, "MCP tools"), mcpToolNames(), "MCP tools");
  const gateRows = sectionLines(text, "测试与门禁脚本").filter((line) => line.startsWith("- `"));
  assertSet(firstCode(gateRows, "测试与门禁脚本"), gateNames(), "测试与门禁脚本");
  const testRows = sectionLines(text, "Rust 测试文件").filter((line) => line.startsWith("- `"));
  assertSet(firstCode(testRows, "Rust 测试文件"), rustTestFiles().map((entry) => entry.path), "Rust 测试文件");
  const docRows = sectionLines(text, "文档登记").filter((line) => line.startsWith("| `"));
  assertSet(firstCode(docRows, "文档登记"), docsRegistry().map((entry) => entry.path), "文档登记");

  for (const path of sectionLines(text, "路由表").flatMap((line) => [...line.matchAll(/`([^`]+)`/g)].map((m) => m[1]))) {
    if (path.includes("${") || path.includes("<") || path.includes("[") || path.includes("*")) continue;
    if (path.startsWith("file://") || path.startsWith("http://") || path.startsWith("https://")) continue;
    if (!knownRoots.has(path.split("/")[0])) continue;
    const absolute = join(ROOT, path);
    if (!existsSync(absolute) || (!statSync(absolute).isFile() && !statSync(absolute).isDirectory())) {
      throw new Error(`路由表引用不存在的文件或目录：${path}`);
    }
  }

  // CodeGraph 索引异步更新，计数只作快照，不进门禁；路径与符号已由源码逐项校验。

  console.log(`[agent-map] 通过：源码 ${files.length}，文档 ${docRows.length}，无 CodeGraph CLI 亦可校验`);
}

if (process.argv.includes("--check")) check();
else generate();
