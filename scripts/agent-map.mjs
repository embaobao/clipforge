const MAP_PATH = join(ROOT, "docs/AGENT_MAP.md");
const INDEX_PATH = join(ROOT, "docs/BUSINESS_INDEX.md");
const LIB_PATH = join(ROOT, "src-tauri/src/lib.rs");
const MCP_PATH = join(ROOT, "src-tauri/src/mcp/specs.rs");
const PACKAGE_PATH = join(ROOT, "package.json");
const MAP_MARKER = "<!-- GENERATED by scripts/agent-map.mjs: pnpm docs:map -->";
const SOURCE_EXTENSION = /\.(ts|tsx|js|mjs|cjs|rs|py|yml|yaml|css|json|html|xml)$/;
